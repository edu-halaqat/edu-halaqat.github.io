'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const css=fs.readFileSync('sanabil-free-live.css','utf8');
const js=fs.readFileSync('sanabil-free-live.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const core=fs.readFileSync('sanabil-live-v12.js','utf8');
assert(!js.includes('sl-peer-compact'),'Old scroll-collapse behavior must be removed');
assert(!css.includes('.sl-peer-panel.sl-peer-compact'),'No dynamic shrinking of entire call panel');
assert(css.includes('.sl-peer-active>.sl-peer-panel{position:relative;top:auto'),'Mobile teacher call panel must not be sticky');
assert(css.includes('.sl-peer-floating .sl-peer-videos{'),'Only the video, not the card, should float');
assert(css.includes('position:fixed'),'Video must remain in view when scrolling down');
assert(css.includes('pointer-events:none'),'Floating video must not steal swipe gestures from outcome cards');
assert(js.includes("const videoStage=create('div','sl-peer-video-stage')"));
assert(js.includes("videoStage.style.minHeight=Math.ceil(videoStage.getBoundingClientRect().height)+'px'"),'Keep original video space and prevent scroll anchoring');
assert(js.includes("videoStage.getBoundingClientRect().bottom<72"),'Float after original video has gone above viewport');
assert(js.includes("document.addEventListener('scroll',s.dockListener,true)"),'Handle nested scrollers');
assert(js.includes("document.removeEventListener('scroll',s.dockListener,true)"),'Clean up nested scroll listener');
assert(js.includes('jump.onclick=locateStudentOutcome')&&js.includes("card.scrollIntoView({behavior:'smooth',block:'start'})"),'Teacher can reach a student outcome card without ending the live session');
assert(!/sl-peer-active>\.sl-peer-panel\{position:sticky/.test(css));
const currentBuild=html.match(/name="sanabil-build" content="([^"]+)"/)?.[1];
assert(currentBuild,'a deployed build must be specified');
assert(core.includes("__SanabilLiveBuild='"+currentBuild+"'"),'core and index release must agree');
assert(html.includes('/sanabil-free-live.js?v=studentjump3'));
assert(html.includes('/sanabil-free-live.js?v='),'student video bridge is versioned');
assert(html.includes('/sanabil-free-live.css?v=pilot3'));
console.log('PASS: mobile panel remains scrollable, video floats without layout collapse, nested scrolling works, release versions agree');
