'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const html=fs.readFileSync('index.html','utf8');
const main=fs.readFileSync('sanabil-live-v12.js','utf8');
const client=fs.readFileSync('sanabil-jadeer-client.js','utf8');
const send=fs.readFileSync('supabase/functions/sanabil-jadeer-send/index.ts','utf8');
const inbox=fs.readFileSync('supabase/functions/sanabil-jadeer-inbox/index.ts','utf8');
assert(html.indexOf('sanabil-jadeer-client.js')<html.indexOf('sanabil-live-v12.js'),'bridge client loads before requests UI');
assert(main.includes('const jadeerReady=window.SanabilJadeer?await window.SanabilJadeer.available(sb()):false;'),'fail closed when receiver missing');
assert(main.includes('value="jadeer" ${jadeerReady?'),'radio must be disabled until receiver configured');
assert(main.includes('id:newRequestId,destination,org_id:'),'destination and stable ID saved in Supabase');
assert(main.includes('window.SanabilJadeer.send(sb(),newRequestId)'),'new nomination must be remotely acknowledged');
assert(main.includes("r.destination==='jadeer'?button('التحقق / إعادة الإرسال'"),'failed deliveries remain retryable without creating duplicates');
assert(client.includes('data?.acknowledged!==true'),'client must reject unacknowledged results');
assert(client.includes('data?.request_id'),'remote receipt must include a real ID');
assert(!client.includes('JADEER_SHARED_SECRET'),'Firebase shared secret must never reach browser');
assert(send.includes('m.org_id===exam.org_id'),'sender must verify organization scope');
assert(send.includes('student.teacher_id!==exam.teacher_id'),'sender must verify student/teacher assignment');
assert(send.includes('confirmation?.acknowledged!==true'),'sender must demand remote Firebase acknowledgement');
assert(send.includes('JADEER_REQUEST_ENDPOINT')&&send.includes('JADEER_SHARED_SECRET'),'remote configured server side only');
assert(inbox.includes('shaHmac(raw,timestamp)'),'webhook requires signed body');
assert(inbox.includes('result.approved!==true'),'unapproved results must be rejected');
assert(inbox.includes('published:false'),'staged inbox must never misreport publication');
assert(!/from\(['"]tests['"]\)\.insert/.test(inbox),'staged inbox must not modify published test scores');
console.log('PASS: staged authenticated outbound, signed inbox, safe matching, acknowledgements, retries, and no false publication');
